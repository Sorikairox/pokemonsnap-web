"""Generate port/build/gen/icall_tab.c (docs/port/MEMORY.md "Indirect calls"; see port/tools/icall.py). Session S3a.

Provenance: reduced from the Conker web port's port/tools/icall_gen.py (the user's own project). Snap has no asm
stubs to register, so only the mismatch dispatcher is generated:
  * `__port_icall_slow`: one case per wasm signature that any registered function has (every game TU lists its
    functions' signatures in port/build/ll/<tag>.v.ll.isig), calling the target with its own type, in two levels
    (groups of 16 cases, each case its own noinline function: Asyncify instruments every case, and one big switch
    becomes a huge function with a huge frame; Conker P380/P387);
  * `port_fsig_name` (signature id -> "r:params") and `port_sig_vi`.
PC-layer functions are not registered (signature 0 = unknown: called on the fast path).
usage: icall_gen.py OUT.c ISIG_DIR"""
import glob, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from icall import sig_id

CT = {'i': 'int', 'I': 'long long', 'f': 'float', 'd': 'double', 'v': 'void'}
GROUP = 16


def generate(out, isig_dir):
    sigs = {'v:i', 'i:i'}
    for f in glob.glob(f'{isig_dir}/*.isig'):
        sigs.update(l.strip() for l in open(f) if l.strip())
    ids = {}
    for s in sorted(sigs):
        i = sig_id(s)
        assert ids.setdefault(i, s) == s, f'signature id collision: {s} {ids[i]}'
    L = ['/* GENERATED by port/tools/icall_gen.py - do not edit. Indirect-call mismatch dispatcher. */',
         '#include "pc_icall.h"', '',
         f'const unsigned port_sig_vi = {sig_id("v:i")}u;',
         f'const unsigned port_sig_ii = {sig_id("i:i")}u;   /* S5: a thread entry promoted by v0.py */', '',
         'const char *port_fsig_name(unsigned id) {', '    switch (id) {']
    L += [f'    case {i}u: return "{s}";' for i, s in sorted(ids.items())]
    L += ['    }', '    return "?";', '}', '']
    for i, s in sorted(ids.items()):
        r, ps = s.split(':')
        args = ', '.join(f'A_{p}(b, n, k, {j})' for j, p in enumerate(ps))
        T = f'{CT[r]} (*)({", ".join(CT[p] for p in ps) or "void"})'
        body = f'(({T})fp)({args}); return 0;' if r == 'v' else f'return R_{r}((({T})fp)({args}), rk);'
        L.append(f'__attribute__((noinline)) static u64_ icall_case_{i}(void *fp, const u64_ *b, int n, unsigned k, '
                 f'unsigned rk) {{ (void)n; (void)k; (void)rk; (void)b; {body} }}')
    groups = [sorted(ids)[g:g + GROUP] for g in range(0, len(ids), GROUP)]
    for g, grp in enumerate(groups):
        L += [f'__attribute__((noinline)) static u64_ icall_group_{g}(void *fp, unsigned tsig, const u64_ *b, int n, '
              'unsigned k, unsigned rk) {', '    switch (tsig) {']
        L += [f'    case {i}u: return icall_case_{i}(fp, b, n, k, rk);' for i in grp]
        L += ['    }', '    return 0;', '}']
    L += ['u64_ __port_icall_slow(void *fp, unsigned tsig, const u64_ *b, int n, unsigned k, unsigned rk) {',
          '    port_icall_note(fp, tsig, n, k, rk);', '    switch (tsig) {']
    for g, grp in enumerate(groups):
        L += [f'    case {i}u:' for i in grp]
        L += [f'        return icall_group_{g}(fp, tsig, b, n, k, rk);']
    L += ['    }', '    return 0;', '}']
    txt = '\n'.join(L) + '\n'
    try:
        if open(out).read() == txt:
            return len(ids)
    except OSError:
        pass
    open(out, 'w').write(txt)
    return len(ids)


if __name__ == '__main__':
    print(f'icall_gen: {generate(sys.argv[1], sys.argv[2])} target signatures')
